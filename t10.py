import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch();pg=await b.new_page(viewport={'width':390,'height':844},device_scale_factor=2)
        errs=[];pg.on('pageerror',lambda e:errs.append('PAGEERR '+str(e)))
        pg.on('console',lambda m:errs.append(m.type+' '+m.text) if m.type in('error','warning') and 'ERR_TUNNEL' not in m.text else None)
        await pg.add_init_script("try{localStorage.setItem('bushido-lang','en')}catch(e){}")
        await pg.goto('file:///home/claude/bushido/game_test.html?dbg=1'); await pg.wait_for_timeout(1500)
        J=lambda q:pg.evaluate("q=>document.querySelector(q).click()",q)
        await J('.x50entry button:nth-child(1)'); await pg.wait_for_timeout(400)
        await J('.x50ov .btn.gold'); await pg.wait_for_timeout(5500)
        print('help shown', await pg.evaluate("()=>!document.querySelector('#overlay').hidden && document.querySelector('#ovCard').innerText.slice(0,40)"))
        await J('#ovCard button.choice'); await pg.wait_for_timeout(1000)
        await pg.screenshot(path='s10_duel.png')
        # exit mid duel -> confirm -> keep playing
        await J('#x50exit'); await pg.wait_for_timeout(300)
        await pg.evaluate("()=>document.querySelectorAll('#ovCard button.choice')[1].click()"); await pg.wait_for_timeout(300)
        print('still xv', await pg.evaluate("()=>!!window.__x50.XV"))
        await J('#x50exit'); await pg.wait_for_timeout(300); await J('#ovCard button.choice'); await pg.wait_for_timeout(600)
        print('after exit', await pg.evaluate("()=>[!!window.__x50.XV,[...document.querySelectorAll('.screen')].filter(s=>!s.hidden).map(s=>s.id)]"))
        # second duel: help should not reappear
        await J('.x50entry button:nth-child(1)'); await pg.wait_for_timeout(400)
        await pg.screenshot(path='s10_setup.png',full_page=True)
        await J('.x50ov .btn.gold'); await pg.wait_for_timeout(5500)
        print('help again?', await pg.evaluate("()=>!document.querySelector('#overlay').hidden"))
        await J('#x50exit'); await pg.wait_for_timeout(300); await J('#ovCard button.choice'); await pg.wait_for_timeout(600)
        # daily open, quick start and exit (no confirm in daily)
        await J('.x50entry button:nth-child(2)'); await pg.wait_for_timeout(400)
        await pg.screenshot(path='s10_daily.png',full_page=True)
        await pg.fill('.x50ov input.hs-name','Dani')
        await J('.x50ov .x50row .btn.gold'); await pg.wait_for_timeout(5500)
        print('daily help', await pg.evaluate("()=>!document.querySelector('#overlay').hidden && document.querySelector('#ovCard').innerText.slice(0,60)"))
        await J('#ovCard button.choice'); await pg.wait_for_timeout(800)
        print('names',await pg.evaluate("()=>[window.__x50.P.name,localStorage.getItem('bushido-player2')]"))
        await J('#x50exit'); await pg.wait_for_timeout(800)
        print('after daily exit', await pg.evaluate("()=>[!!window.__x50.XV,[...document.querySelectorAll('.screen')].filter(s=>!s.hidden).map(s=>s.id),document.querySelector('.x50entry button:nth-child(4) small').textContent]"))
        print('\n'.join(errs))
        await b.close()
asyncio.run(main())
